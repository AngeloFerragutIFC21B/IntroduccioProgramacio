console.log(true && true);
console.log(true && false);
console.log("");
/*
&& (AND): És un operador logic que retorna "true"
si ambes condicions es cumnpleixen o son vertaderes.
*/

console.log(true || true);
console.log(true || false);
console.log("");
/*
|| (OR): És un operador logic que retorna "true"
si qualsevol dels valors es compleix o es vertader.
*/

console.log(!true);
console.log(!false);
console.log("");
/*
|| (OR): És un operador logic que retorna el
contrari del valor original apart de convertir-lo
en boolean.
*/